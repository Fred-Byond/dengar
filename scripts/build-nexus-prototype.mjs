/**
 * Generate the self-contained AUREN Nexus prototype.
 *
 * Same discipline as the other two generators: the prototype gets no copy of
 * the vocabulary, the derivation rules, the corpus or the analytics. It gets
 * the compiled modules, injected between markers — and it gets the console's
 * governance spine too, so the gate that blocks a release in the Nexus is
 * literally the same ten tests that block one in /console.
 *
 *   npm run nexus
 *
 * Every module in ORDER is dependency-free at runtime (they import only types
 * from each other, which erase at compile), which is what makes a plain
 * concatenation safe here without a bundler.
 */

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
/**
 * Both prototypes carry the same markers and get the same engine. The
 * Supervision Console is not a second implementation of the analytics — it is
 * the same compiled modules, so a verdict shown to a supervisor and a verdict
 * computed in the Nexus cannot drift.
 */
const TARGETS = [
  join(ROOT, "public/prototypes/auren-nexus.html"),
  join(ROOT, "public/prototypes/auren-console.html"),
];
const START = "/* AUREN-NEXUS-START — generated by scripts/build-nexus-prototype.mjs */";
const END = "/* AUREN-NEXUS-END */";

/** Dependency order. Each file's exports are visible to the next. */
const ORDER = [
  "lib/console/schema.js",
  "lib/auren/objects.js",
  "lib/console/verticals.js",
  "lib/console/library.js",
  "lib/console/gate.js",
  "lib/console/release.js",
  "lib/nexus/vocabulary.js",
  "lib/nexus/signal.js",
  "lib/nexus/derive.js",
  "lib/nexus/corpus.js",
  "lib/nexus/cohort.js",
  "lib/nexus/participants.js",
];

const out = mkdtempSync(join(tmpdir(), "auren-nexus-"));

try {
  const cfg = join(out, "tsconfig.json");
  writeFileSync(
    cfg,
    JSON.stringify({
      compilerOptions: {
        target: "es2022",
        module: "es2022",
        moduleResolution: "bundler",
        skipLibCheck: true,
        strict: true,
        outDir: out,
        rootDir: join(ROOT, "src"),
        paths: { "@/*": [join(ROOT, "src/*")] },
      },
      include: [
        join(ROOT, "src/lib/console/**/*.ts"),
        join(ROOT, "src/lib/auren/**/*.ts"),
        join(ROOT, "src/lib/nexus/**/*.ts"),
      ],
    })
  );

  execFileSync(join(ROOT, "node_modules/.bin/tsc"), ["-p", cfg], { stdio: "inherit" });

  // Strip module syntax and concatenate. `export` becomes a plain declaration;
  // every `import` line is dropped because the symbol is already in scope.
  const parts = ORDER.map((rel) => {
    const src = readFileSync(join(out, rel), "utf8");
    const body = src
      .replace(/^\s*import[\s\S]*?from\s+["'][^"']+["'];?\s*$/gm, "")
      .replace(/^\s*import\s+["'][^"']+["'];?\s*$/gm, "")
      .replace(/^export\s+/gm, "")
      .replace(/^\s*export\s*\{[^}]*\};?\s*$/gm, "");
    return `/* ── ${rel} ─────────────────────────────────── */\n${body.trim()}\n`;
  });

  const block = `${START}\n${parts.join("\n")}\n`;

  // Concatenation makes every module-private name global, so a name used twice
  // across two files compiles here and throws at load. Catch it at build time.
  const seen = new Map();
  const decl = /^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm;
  for (const part of parts) {
    const rel = part.slice(part.indexOf("── ") + 3, part.indexOf(" ───"));
    for (const m of part.matchAll(decl)) {
      const prior = seen.get(m[1]);
      if (prior && prior !== rel) {
        throw new Error(
          `Duplicate top-level declaration "${m[1]}" in ${rel} and ${prior}. ` +
            `Concatenation puts both in one scope — rename one.`
        );
      }
      seen.set(m[1], rel);
    }
  }

  for (const target of TARGETS) {
    const html = readFileSync(target, "utf8");
    const a = html.indexOf(START);
    const b = html.indexOf(END);
    if (a === -1 || b === -1) {
      throw new Error(`Markers not found in ${target}. Expected ${START} … ${END}.`);
    }
    writeFileSync(target, html.slice(0, a) + block + html.slice(b), "utf8");
  }

  console.log(
    `Injected the Nexus engine into ${TARGETS.length} prototypes: ${ORDER.length} modules, ` +
      `${block.length.toLocaleString()} bytes each. Vocabulary, derivation, corpus, analytics, ` +
      `participants and the console's own publish gate — one engine, not a second copy.`
  );
} finally {
  rmSync(out, { recursive: true, force: true });
}
