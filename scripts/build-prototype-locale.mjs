/**
 * Generate the prototype's locale table from the canonical TypeScript.
 *
 * The self-contained prototype at public/prototypes/auren-rehearsal.html and
 * the React build at /auren must never disagree about what the coach says —
 * a demo that has drifted from the product is worse than no demo. So rather
 * than maintaining the copy twice, this compiles src/lib/auren/{i18n,objects}.ts
 * and injects the result between the markers in the prototype.
 *
 *   npm run locale
 *
 * Both files are dependency-free by design (objects.ts imports only i18n.ts),
 * which is what makes this possible without a bundler.
 */

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = resolve(import.meta.dirname, "..");
const PROTOTYPE = join(ROOT, "public/prototypes/auren-rehearsal.html");
const START = "/* AUREN-LOCALE-START — generated by scripts/build-prototype-locale.mjs */";
const END = "/* AUREN-LOCALE-END */";

const out = mkdtempSync(join(tmpdir(), "auren-locale-"));

try {
  execFileSync(
    join(ROOT, "node_modules/.bin/tsc"),
    [
      join(ROOT, "src/lib/auren/i18n.ts"),
      join(ROOT, "src/lib/auren/objects.ts"),
      "--outDir", out,
      "--module", "es2022",
      "--target", "es2022",
      "--moduleResolution", "bundler",
      "--skipLibCheck",
    ],
    { stdio: "inherit" }
  );

  const i18n = await import(pathToFileURL(join(out, "i18n.js")).href);
  const objects = await import(pathToFileURL(join(out, "objects.js")).href);

  const locale = {
    languages: i18n.LANGUAGES,
    ui: i18n.UI,
    elements: objects.ELEMENTS,
    failures: objects.FAILURE_SIGNATURES,
    questions: objects.QUESTIONS,
    challenges: objects.CHALLENGES,
    verification: objects.VERIFICATION_ACTIONS,
    protectMarkers: objects.PROTECT_MARKERS,
    elementBudget: objects.ELEMENT_BUDGET,
  };

  const html = readFileSync(PROTOTYPE, "utf8");
  const a = html.indexOf(START);
  const b = html.indexOf(END);
  if (a === -1 || b === -1) {
    throw new Error(
      `Locale markers not found in ${PROTOTYPE}. Expected ${START} … ${END}.`
    );
  }

  const block = `${START}\nconst L = ${JSON.stringify(locale, null, 1)};\n`;
  writeFileSync(PROTOTYPE, html.slice(0, a) + block + html.slice(b), "utf8");

  const n = Object.keys(i18n.UI).length;
  console.log(
    `Injected locale into the prototype: ${i18n.LANGUAGES.length} languages, ` +
      `${n} UI strings, ${objects.QUESTIONS.length} questions, ` +
      `${objects.CHALLENGES.length} challenges.`
  );
} finally {
  rmSync(out, { recursive: true, force: true });
}
