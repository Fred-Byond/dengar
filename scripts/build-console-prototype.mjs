/**
 * Generate the self-contained Knowledge Authority prototype.
 *
 * Same discipline as the AUREN locale generator: the console at /console and
 * the standalone prototype must not drift, so the prototype does not get its
 * own copy of the schema, the libraries or the gate. This compiles the real
 * modules and injects them between markers in the HTML.
 *
 *   npm run console
 *
 * src/lib/console/* and src/lib/auren/objects.ts are dependency-free by design
 * (objects.ts imports only TYPES from i18n, which erase at compile), which is
 * what makes a plain concatenation safe here without a bundler.
 */

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const PROTOTYPE = join(ROOT, "public/prototypes/knowledge-authority.html");
const START = "/* AUREN-CONSOLE-START — generated by scripts/build-console-prototype.mjs */";
const END = "/* AUREN-CONSOLE-END */";

/** Dependency order. Each file's exports are visible to the next. */
const ORDER = [
  "lib/console/schema.js",
  "lib/auren/objects.js",
  "lib/console/verticals.js",
  "lib/console/library.js",
  "lib/console/gate.js",
  "lib/console/release.js",
];

const out = mkdtempSync(join(tmpdir(), "auren-console-"));

try {
  const cfg = join(out, "tsconfig.json");
  writeFileSync(
    cfg,
    JSON.stringify({
      compilerOptions: {
        target: "es2022",
        module: "es2022",
        moduleResolution: "bundler",
        skipLibCheck: true,
        strict: true,
        outDir: out,
        rootDir: join(ROOT, "src"),
        paths: { "@/*": [join(ROOT, "src/*")] },
      },
      include: [
        join(ROOT, "src/lib/console/**/*.ts"),
        join(ROOT, "src/lib/auren/**/*.ts"),
      ],
    })
  );

  execFileSync(join(ROOT, "node_modules/.bin/tsc"), ["-p", cfg], { stdio: "inherit" });

  // Strip module syntax and concatenate. `export` becomes a plain declaration;
  // every `import` line is dropped because the symbol is already in scope.
  const parts = ORDER.map((rel) => {
    const src = readFileSync(join(out, rel), "utf8");
    const body = src
      .replace(/^\s*import[\s\S]*?from\s+["'][^"']+["'];?\s*$/gm, "")
      .replace(/^\s*import\s+["'][^"']+["'];?\s*$/gm, "")
      .replace(/^export\s+/gm, "")
      .replace(/^\s*export\s*\{[^}]*\};?\s*$/gm, "");
    return `/* ── ${rel} ─────────────────────────────────── */\n${body.trim()}\n`;
  });

  const block = `${START}\n${parts.join("\n")}\n`;

  const html = readFileSync(PROTOTYPE, "utf8");
  const a = html.indexOf(START);
  const b = html.indexOf(END);
  if (a === -1 || b === -1) {
    throw new Error(`Markers not found in ${PROTOTYPE}. Expected ${START} … ${END}.`);
  }
  writeFileSync(PROTOTYPE, html.slice(0, a) + block + html.slice(b), "utf8");

  console.log(
    `Injected the console engine into the prototype: ${ORDER.length} modules, ` +
      `${block.length.toLocaleString()} bytes. Schema, libraries and gate are the same code as /console.`
  );
} finally {
  rmSync(out, { recursive: true, force: true });
}
